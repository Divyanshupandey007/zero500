import time
from pydantic import BaseModel,Field
from google import genai
from google.genai import types
from app.config import settings
from app.models.incident import IncidentDetail
from app.models.investigation import InvestigationReport
from app.models.evaluation import TestCaseResult,EvaluationSuiteReport
from app.data.eval_dataset import EVAL_GROUND_TRUTH
from app.data.synthetic import SYNTHETIC_INCIDENTS
from app.services.investigator import investigator_service

class JudgeScore(BaseModel):
    alignment_score:float=Field(ge=0.0,le=1.0,description="Score 0.0 to 1.0 on how well the hypothesis matches ground truth")
    reasoning:str=Field(description="Explanation of the score")

class EvaluationEngine:
    def __init__(self):
        self.gemini_client=genai.Client(api_key=settings.GEMINI_API_KEY)

    def _eval_faithfulness(self,incident:IncidentDetail,report:InvestigationReport)->float:
        """Check if cited evidence items exist in raw logs or metrics snapshot"""
        if not report.evidence:
            return 0.0

        all_raw_text=" ".join([
            log.message+" "+log.timestamp.isoformat()
            for log in incident.logs
        ])
        for k,v in incident.metrics_snapshot.items():
            all_raw_text+=f" {k} {v}"

        grounded_count=0
        for ev in report.evidence:
            # Check if source/detail fragments appear in telemetry
            source_tokens=ev.source.lower().split()
            matches=any(token in all_raw_text.lower() for token in source_tokens if len(token)>3)
            if matches:
                grounded_count+=1

        return round(grounded_count/len(report.evidence),2)

    def _judge_diagnosis_accuracy(self,ground_truth:str,predicted_cause:str)->float:
        """Use LLM as an objective judge to score semantic alignment"""
        prompt=f"""
Compare the suspected root cause generated by an AI SRE with the verified ground truth root cause.
Assign a score from 0.0 (completely inaccurate) to 1.0 (accurate, captures the core technical failure).

Ground Truth:
{ground_truth}

AI Predicted Root Cause:
{predicted_cause}
"""
        response=self.gemini_client.models.generate_content(
            model=settings.GEMINI_MODEL,
            contents=prompt,
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                response_schema=JudgeScore,
                temperature=0.0
            )
        )
        judge_res:JudgeScore=response.parsed
        return judge_res.alignment_score

    def run_suite(self)->EvaluationSuiteReport:
        results=[]
        incident_map={inc.id:inc for inc in SYNTHETIC_INCIDENTS}

        for test in EVAL_GROUND_TRUTH:
            inc_id=test["incident_id"]
            incident=incident_map.get(inc_id)
            if not incident:
                continue

            start_time=time.time()
            report:InvestigationReport=investigator_service.investigate(incident)
            latency=round(time.time()-start_time,2)

            # Retrieval Eval
            retrieval_success=any(
                test["expected_runbook_keyword"].lower() in mb.title.lower()
                for mb in report.matched_runbooks
            )

            # Faithfulness Eval
            faithfulness=self._eval_faithfulness(incident,report)

            # LLM as a Judge Eval
            accuracy=self._judge_diagnosis_accuracy(
                test["ground_truth_root_cause"],
                report.suspected_root_cause
            )

            results.append(TestCaseResult(
                incident_id=inc_id,
                retrieval_success=retrieval_success,
                faithfulness_score=faithfulness,
                diagnosis_alignment_score=accuracy,
                latency_seconds=latency,
                details={
                    "predicted_root_cause":report.suspected_root_cause,
                    "top_runbook_retrieved":report.matched_runbooks[0].title if report.matched_runbooks else "None"
                }
            ))

        total=len(results)
        recall=round(sum(1 for r in results if r.retrieval_success)/total,2)
        avg_faith=round(sum(r.faithfulness_score for r in results)/total,2)
        avg_acc=round(sum(r.diagnosis_alignment_score for r in results)/total,2)
        avg_lat=round(sum(r.latency_seconds for r in results)/total,2)

        return EvaluationSuiteReport(
            total_test_case=total,
            retrieval_recall=recall,
            average_faithfulness=avg_faith,
            average_diagnosis_accuracy=avg_acc,
            average_latency_seconds=avg_lat,
            test_cases=results
        )

evaluation_engine=EvaluationEngine()